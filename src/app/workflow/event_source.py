"""Event source connecting LangGraph to the SSE layer."""

from collections.abc import AsyncIterator

from app.models import AuditEvent, ReviewRequest
from app.workflow.graph import SQLCritic, SQLGenerator, build_review_graph


class GraphEventSource:
    """Produce review events from a compiled LangGraph workflow."""

    def __init__(
        self,
        generator: SQLGenerator,
        critic: SQLCritic,
    ) -> None:
        """Build the workflow from generator and critic objects."""
        self._graph = build_review_graph(
            generator=generator,
            critic=critic,
        )

    async def stream(
        self,
        request: ReviewRequest,
    ) -> AsyncIterator[AuditEvent]:
        """Yield events as LangGraph nodes complete."""
        emitted_event_count = 0

        async for update in self._graph.astream(
            {
                "request": request,
                "events": [],
            },
            stream_mode="updates",
        ):
            for node_state in update.values():
                if not isinstance(node_state, dict):
                    continue

                raw_events = node_state.get("events", [])

                if not isinstance(raw_events, list):
                    continue

                new_events = raw_events[emitted_event_count:]

                for event in new_events:
                    if isinstance(event, AuditEvent):
                        yield event

                emitted_event_count = len(raw_events)

